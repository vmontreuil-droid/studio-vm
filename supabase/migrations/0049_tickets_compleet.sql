-- ---------- 6. Trigger: elk nieuw bericht werkt het ticket bij ----------
create or replace function public.ticket_na_bericht()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.tickets
     set laatste_bericht_op = new.created_at,
         laatste_afzender   = new.sender,
         laatste_fragment   = left(regexp_replace(new.body, '\s+', ' ', 'g'), 200),
         wacht_op           = case when new.sender = 'studio' then 'klant' else 'studio' end,
         eerste_antwoord_op = case when new.sender = 'studio'
                                   then coalesce(eerste_antwoord_op, new.created_at)
                                   else eerste_antwoord_op end,
         klant_gelezen_op   = case when new.sender = 'klant'
                                   then greatest(coalesce(klant_gelezen_op, new.created_at), new.created_at)
                                   else klant_gelezen_op end,
         studio_gelezen_op  = case when new.sender = 'studio'
                                   then greatest(coalesce(studio_gelezen_op, new.created_at), new.created_at)
                                   else studio_gelezen_op end,
         herinnerd_op       = null,
         updated_at         = now()
   where id = new.ticket_id;
  return new;
end;
$$;

drop trigger if exists ticket_na_bericht on public.ticket_messages;
create trigger ticket_na_bericht
  after insert on public.ticket_messages
  for each row execute function public.ticket_na_bericht();

-- ---------- 7. Bijlagen, interne notities, revisie-uren ----------
create table if not exists public.ticket_bijlagen (
  id          uuid primary key default gen_random_uuid(),
  created_at  timestamptz not null default now(),
  ticket_id   uuid not null references public.tickets (id) on delete cascade,
  message_id  uuid references public.ticket_messages (id) on delete set null,
  door        text not null check (door in ('klant', 'studio')),
  naam        text not null check (char_length(naam) between 1 and 200),
  pad         text not null unique,
  grootte     bigint,
  mime        text
);
create index if not exists ticket_bijlagen_ticket_idx on public.ticket_bijlagen (ticket_id);

-- Interne notities: NOOIT zichtbaar voor de klant (geen policies).
create table if not exists public.ticket_notities (
  id          uuid primary key default gen_random_uuid(),
  created_at  timestamptz not null default now(),
  ticket_id   uuid not null references public.tickets (id) on delete cascade,
  body        text not null check (char_length(body) between 1 and 10000)
);
create index if not exists ticket_notities_ticket_idx on public.ticket_notities (ticket_id, created_at);

-- Revisie-uren per ticket; tarief = momentopname van de projectcategorie.
create table if not exists public.ticket_uren (
  id               uuid primary key default gen_random_uuid(),
  created_at       timestamptz not null default now(),
  ticket_id        uuid not null references public.tickets (id) on delete cascade,
  project_id       uuid references public.projecten (id) on delete set null,
  uren             numeric(6, 2) not null check (uren > 0 and uren <= 999),
  tarief_cent      integer not null check (tarief_cent >= 0),
  omschrijving     text check (omschrijving is null or char_length(omschrijving) <= 300),
  invoice_id       uuid references public.invoices (id) on delete set null,
  naar_project_op  timestamptz
);
create index if not exists ticket_uren_ticket_idx on public.ticket_uren (ticket_id);
create index if not exists ticket_uren_open_idx
  on public.ticket_uren (project_id) where invoice_id is null and naar_project_op is null;

-- ---------- 8. Facturen: revisiefactuur <-> ticket, btw-verlegging per factuur ----------
alter table public.invoices
  add column if not exists ticket_id   uuid references public.tickets (id) on delete set null,
  add column if not exists vat_reverse boolean;
create index if not exists invoices_ticket_idx
  on public.invoices (ticket_id) where ticket_id is not null;

-- ---------- 9. Rechten (RLS) ----------
-- Lezen: klant ziet enkel zijn eigen tickets/berichten/bijlagen (hoofdletterongevoelig).
drop policy if exists tickets_own on public.tickets;
create policy tickets_own on public.tickets
  for select to authenticated
  using (lower(client_email) = public.current_email());

drop policy if exists tmsg_own on public.ticket_messages;
create policy tmsg_own on public.ticket_messages
  for select to authenticated
  using (
    exists (
      select 1 from public.tickets t
       where t.id = ticket_messages.ticket_id
         and lower(t.client_email) = public.current_email()
    )
  );

alter table public.ticket_bijlagen enable row level security;
alter table public.ticket_notities enable row level security;
alter table public.ticket_uren     enable row level security;

drop policy if exists tbijl_own on public.ticket_bijlagen;
create policy tbijl_own on public.ticket_bijlagen
  for select to authenticated
  using (
    exists (
      select 1 from public.tickets t
       where t.id = ticket_bijlagen.ticket_id
         and lower(t.client_email) = public.current_email()
    )
  );
-- ticket_notities en ticket_uren: bewust GEEN policies -> enkel de service-role.

-- Schrijven: enkel nog de server (service-role) na eigendomscontrole.
-- 'revoke all' (ook truncate/references/trigger, waar RLS niet voor geldt),
-- daarna enkel lezen terug voor aangemelde klanten (de policies hierboven).
drop policy if exists tickets_create on public.tickets;
drop policy if exists tmsg_create on public.ticket_messages;
revoke all on public.tickets, public.ticket_messages, public.ticket_bijlagen from anon, authenticated;
grant select on public.tickets, public.ticket_messages, public.ticket_bijlagen to authenticated;
revoke all on public.ticket_notities from anon, authenticated;
revoke all on public.ticket_uren     from anon, authenticated;

